import { readdir, readFile, writeFile } from 'node:fs/promises';

const sourceDir = new URL('../src/cloud/', import.meta.url);
const files = (await readdir(sourceDir)).filter(name => name.endsWith('.fragment.js')).sort();
const fragments = [];

for (const file of files) {
  const source = await readFile(new URL(file, sourceDir), 'utf8');
  const marker = /\/\* @fragment (\d{4}) \*\//g;
  const matches = [...source.matchAll(marker)];
  if (!matches.length) throw new Error(`${file}: missing fragment marker`);
  matches.forEach((match, index) => {
    const start = match.index + match[0].length;
    const end = matches[index + 1]?.index ?? source.length;
    fragments.push({ order: Number(match[1]), file, source: source.slice(start, end).trimEnd() });
  });
}

fragments.sort((a, b) => a.order - b.order);
const orders = new Set();
for (const fragment of fragments) {
  if (orders.has(fragment.order)) throw new Error(`duplicate fragment order ${fragment.order}`);
  orders.add(fragment.order);
}

const output = `// Generated by npm run frontend:build. Edit src/cloud/*.fragment.js.\n(() => {${fragments.map(x => x.source).join('\n')}\n})();\n`;
const outputUrl = new URL('../cloud.js', import.meta.url);
if (process.argv.includes('--check')) {
  const current = await readFile(outputUrl, 'utf8');
  if (current !== output) throw new Error('cloud.js is stale; run npm run frontend:build');
  console.log(`cloud.js matches ${fragments.length} ordered source fragments.`);
} else {
  await writeFile(outputUrl, output, 'utf8');
  console.log(`Built cloud.js from ${fragments.length} ordered fragments.`);
}
